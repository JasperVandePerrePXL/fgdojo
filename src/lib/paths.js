// Absolute paths of the project's important folders and files.
// Import these instead of building "../../data/..." paths in every module.
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/** Repository root (this file lives in `src/lib/`). */
export const PROJECT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

/** Hand-maintained configuration and the raw start.gg events. */
export const DATA_DIR = path.join(PROJECT_ROOT, 'data');
/** Static files copied into the website by Vite (includes the generated leaderboard JSON). */
export const PUBLIC_DIR = path.join(PROJECT_ROOT, 'public');
/** Output of `vite build`; this is what gets deployed to S3. */
export const DIST_DIR = path.join(PROJECT_ROOT, 'dist');

export const TOURNAMENT_SLUGS_FILE = path.join(DATA_DIR, 'tournament_slugs.json');
export const GAMES_FILE = path.join(DATA_DIR, 'games.json');
export const HIDDEN_PLAYERS_FILE = path.join(DATA_DIR, 'hidden_players.json');
/** The single JSON file the website loads. Generated by `npm run process`. */
export const LEADERBOARDS_FILE = path.join(PUBLIC_DIR, 'data', 'leaderboards.json');
